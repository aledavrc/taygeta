"""Taygeta curricular taxonomy: human-readable course names.

Presentation helpers for the curricular domain, which delegate to the
internationalization layer (:mod:`taygeta.i18n`):

* :func:`title_case_slug`: ``snake_case`` slug → readable title in the active
  language (with its own set of minor words).
* :func:`format_course_name`: course name localized to the active language,
  resolved through the taxonomy provider (database) with a fallback to
  :func:`title_case_slug`.
* :class:`TaxonomyNames` and :func:`filter_taxonomy_names`: carry the readable
  names (es/en) that the LLM generates during structuring up to confirmation,
  where they are persisted with ``source='llm'``.

Curricular slugs remain **stable data** and are never translated; only the
presentation name varies. Readable names live in the ``taxonomy_labels`` table
(not in the code).

Canonicalization of ``course``, ``topic``, ``subtopic`` and prerequisites is
100% dynamic: it is read from the live database (see
:meth:`taygeta.server.db.Database.get_live_taxonomy_tree` and
:meth:`taygeta.server.db.Database.list_prerequisites`) and injected into the
structuring system prompts. There are no hardcoded alias dictionaries or closed
vocabulary.

None of these helpers stores solutions or correct answers: they are presentation
names only.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from taygeta.core.schema import Slug
from taygeta.i18n import course_name, title_case_slug

__all__ = [
    "TAXONOMY_KINDS",
    "TaxonomyKind",
    "TaxonomyNames",
    "filter_taxonomy_names",
    "format_course_name",
    "title_case_slug",
]

#: Taxonomy entry kinds that can have a human-readable name.
TaxonomyKind = Literal["course", "topic", "subtopic", "prerequisite"]

TAXONOMY_KINDS: tuple[TaxonomyKind, ...] = ("course", "topic", "subtopic", "prerequisite")


class TaxonomyNames(BaseModel):
    """Human-readable names (es/en) of a taxonomy entry.

    Travels from structuring (generated by the LLM) up to confirmation, where it
    is persisted in ``taxonomy_labels`` with ``source='llm'``. The names are for
    presentation only: they never replace the slug nor contain solutions.
    """

    model_config = ConfigDict(extra="forbid")

    kind: TaxonomyKind
    slug: Slug
    parent_slug: str = ""
    es: str = Field(..., min_length=1, description="Human-readable name in Spanish.")
    en: str = Field(..., min_length=1, description="Human-readable name in English.")

    def locale_labels(self) -> list[tuple[str, str]]:
        """Return the ``(locale, label)`` pairs ready to persist."""
        return [("es", self.es), ("en", self.en)]


def filter_taxonomy_names(
    names: Iterable[TaxonomyNames],
    *,
    course: str,
    topic: str,
    subtopic: str | None,
    prerequisites: Iterable[str],
) -> list[TaxonomyNames]:
    """Keep only the names that still match the final classification.

    Human review may edit the course, topic, subtopic or prerequisites, so the
    names generated by the LLM that no longer correspond to those slugs are
    discarded. Topics and subtopics are re-parented to the final course.
    """
    prerequisite_set = set(prerequisites)
    kept: list[TaxonomyNames] = []
    for entry in names:
        if entry.kind == "course":
            if entry.slug == course:
                kept.append(entry)
        elif entry.kind == "topic":
            if entry.slug == topic:
                kept.append(entry.model_copy(update={"parent_slug": course}))
        elif entry.kind == "subtopic":
            if subtopic and entry.slug == subtopic:
                kept.append(entry.model_copy(update={"parent_slug": course}))
        elif entry.kind == "prerequisite" and entry.slug in prerequisite_set:
            kept.append(entry.model_copy(update={"parent_slug": ""}))
    return kept


def format_course_name(slug: str, *, locale: str | None = None) -> str:
    """Return the human-readable, localized name of a course.

    Resolves the slug through the taxonomy provider (typically backed by the
    database) and applies :func:`title_case_slug` as a fallback for slugs without
    a cataloged name.
    """
    return course_name(slug, locale=locale)
